def expand_major(major: str, max_terms: int = 12) -> List[str]:
    """输入专业关键词，返回 [原词 + 同大类相关词]，用于扩大召回。"""
    major = (major or "").strip()
    if not major:
        return []
    terms = [major]
    for group_terms in MAJOR_GROUPS.values():
        if any(major in t or t in major for t in group_terms):
            for t in group_terms:
                if t not in terms:
                    terms.append(t)
            break
    return terms[:max_terms]
